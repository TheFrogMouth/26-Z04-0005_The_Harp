"""ADC Driver: THS4522 channel A as a single-ended to differential driver; channel B powered down."""
from layouts.common import u, U, shunt, series


def layout(L):
    L.text(L.sheet.notes[0], u(8), u(6))
    X, Y = u(60), u(40)
    L.at('U601', X, Y, unit=1, ref_pos=(u(50), u(46.5), 'left'), val_pos=(u(50), u(48), 'left'))
    # ---- inputs: EFFECT_IN_BUF (top) and VCOM_A reference (bottom)
    for y, net, cap, res, pin in ((u(34), 'EFFECT_IN_BUF', 'C601', 'R601', '2'), (u(46), 'VCOM_A', 'C602', 'R602', '3')):
        L.gl(net, (u(26), y), 'left')
        L.w((u(26), y), (u(34), y))
        shunt(L, cap, u(30), y)
        series(L, res, u(35.5), y)
        L.w((res, '2'), (u(50), y), 'V', ('U601', pin))
    # ---- outputs through 40.2R to ADC_N (top) / ADC_P (bottom)
    L.w(('U601', '15'), (u(71), u(38)))
    series(L, 'R605', u(72.5), u(38))
    L.w(('R605', '2'), (u(90), u(38)))
    L.w(('U601', '14'), (u(71), u(42)))
    series(L, 'R606', u(72.5), u(42))
    L.w(('R606', '2'), (u(86), u(42)))
    L.at('C605', u(80), u(40), ang=180)                          # across ADC_P (pin 1, below) / ADC_N
    L.w((u(80), u(38)), ('C605', '2'))
    L.w(('C605', '1'), (u(80), u(42)))
    shunt(L, 'C606', u(83), u(42))
    L.gl('ADC_P', (u(86), u(42)), 'right')
    shunt(L, 'C607', u(92), u(38))
    L.w((u(90), u(38)), (u(96), u(38)))
    L.gl('ADC_N', (u(96), u(38)), 'right')
    # ---- feedback: C603 / C604 to the outputs, R603 / R604 to the filtered outputs
    L.w((u(44), u(34)), (u(44), u(23)), (u(53), u(23)))
    series(L, 'C603', u(54.5), u(23))
    L.w(('C603', '2'), (u(69), u(23)), (u(69), u(38)))
    L.w((u(40), u(34)), (u(40), u(19)), (u(60), u(19)))
    series(L, 'R603', u(61.5), u(19))
    L.w(('R603', '2'), (u(78), u(19)), (u(78), u(38)))
    L.w((u(44), u(46)), (u(44), u(59)), (u(53), u(59)))
    series(L, 'C604', u(54.5), u(59))
    L.w(('C604', '2'), (u(69), u(59)), (u(69), u(42)))
    L.w((u(40), u(46)), (u(40), u(63)), (u(60), u(63)))
    series(L, 'R604', u(61.5), u(63))
    L.w(('R604', '2'), (u(78), u(63)), (u(78), u(42)))
    # ---- supply and VOCM
    L.w(('U601', '13'), (u(58.5), u(29)))
    L.pwr('+5V', (u(58.5), u(29)), 'up')
    L.w(('U601', '1'), (u(60), u(31)), (u(58.5), u(31)))
    L.gnd(('U601', '16'), length=U)
    L.w(('U601', '4'), (u(60), u(51)), (u(53), u(51)))
    shunt(L, 'C608', u(57), u(51))
    L.gl('VCOM_B', (u(53), u(51)), 'left')
    # ---- supply decoupling
    L.pwr('+5V', (u(90), u(22)), 'up')
    L.w((u(90), u(22)), (u(90), u(24)), (u(96), u(24)))
    shunt(L, 'C609', u(92), u(24))
    shunt(L, 'C610', u(96), u(24))
    # ---- channel B, powered down: inputs, VOCM and VSS to GND, PD high is GND? no: PD pin 5 to GND per spec
    X2, Y2 = u(112), u(40)
    L.at('U601', X2, Y2, unit=2, ref_pos=(u(104), u(46.5), 'left'), val_pos=(u(104), u(48), 'left'))
    L.w(('U601', '6', 2), (u(102), u(38)), (u(102), u(49)))
    L.w(('U601', '7', 2), (u(102), u(42)))
    L.gnd((u(102), u(49)))
    L.w(('U601', '12', 2), (u(110.5), u(49)), (u(112), u(49)))
    L.w(('U601', '8', 2), (u(112), u(49)))
    L.gnd((u(112), u(49)))
    L.w(('U601', '5', 2), (u(112), u(32)), (u(121), u(32)), (u(121), u(49)))
    L.gnd((u(121), u(49)))
    L.w(('U601', '9', 2), (u(110.5), u(29)))
    L.pwr('+5V', (u(110.5), u(29)), 'up')
    L.nc('U601', '10', 2)
    L.nc('U601', '11', 2)
